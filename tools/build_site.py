#!/usr/bin/env python3
"""Build the deployed site into --out: site/ copied as is, the release's install.sh, the agent
documents emitted by tools/site_sync.py, the /docs/ pages generated by tools/site_docs.py, and
every HTML page's inline script, styles and JSON-LD minified.

The language documentation comes from a checkout of SamGalanakis/hirsel (--hirsel-repo, or
HIRSEL_REPO), aligned to --release-tag: by default the newest v* tag in that checkout, or its
working tree when it has none or `--release-tag main` is passed. The source stays readable;
only the deployed copy is minified. Every other file is copied byte for byte.

The installer has one source: the install.sh asset of the Hirsel release, checked against that
release's SHA256SUMS before it is passed as --installer (the Dockerfile does both). The build
fails unless the installer's platform arms are exactly the platforms the site's copy names
(SUPPORTED_TARGETS).

Usage: tools/build_site.py --hirsel-repo PATH --installer INSTALL_SH [--out _site] [--release-tag TAG]
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ESBUILD = ["npx", "--yes", "esbuild@0.28.2"]
TOOLS = Path(__file__).resolve().parent
SITE = TOOLS.parent / "site"
JSONLD_TAG = '<script type="application/ld+json">'
# The targets the hand-written copy (site/index.html, tools/site_docs*.py, tools/site_sync.py)
# names as supported. Change them together with that copy.
SUPPORTED_TARGETS = {"x86_64-unknown-linux-gnu", "aarch64-apple-darwin"}


_ESBUILD_CACHE: dict[tuple[str, str], str] = {}
_NODE_CHECKED: set[str] = set()


def esbuild(code: str, loader: str) -> str:
    key = (loader, code)
    if key in _ESBUILD_CACHE:
        return _ESBUILD_CACHE[key]
    out = subprocess.run(
        [*ESBUILD, f"--loader={loader}", "--minify", "--charset=utf8"],
        input=code.encode(), capture_output=True, check=True,
    ).stdout.decode().rstrip("\n")
    if not out.strip():
        sys.exit(f"build_site: esbuild returned nothing for a {loader} block")
    _ESBUILD_CACHE[key] = out
    return out


def splice(html: str, tag: str, loader: str) -> str:
    """Minify the body of every bare <tag>...</tag>, splicing by index (no regex replacement)."""
    parts, at = [], 0
    for m in re.finditer(rf"<{tag}>(.*?)</{tag}>", html, re.S):
        body = esbuild(m.group(1), loader)
        if f"</{tag}" in body.lower():
            sys.exit(f"build_site: minified {loader} contains </{tag}")
        parts += [html[at:m.start(1)], body]
        at = m.end(1)
    return "".join(parts) + html[at:]


def splice_jsonld(html: str) -> str:
    """Validate and minify every <script type="application/ld+json">...</script> block."""
    parts, at = [], 0
    pattern = re.compile(re.escape(JSONLD_TAG) + r"(.*?)</script>", re.S)
    for m in pattern.finditer(html):
        parsed = json.loads(m.group(1))
        body = json.dumps(parsed, separators=(",", ":"), ensure_ascii=False)
        if "</script" in body.lower():
            sys.exit("build_site: minified JSON-LD contains </script")
        parts += [html[at:m.start(1)], body]
        at = m.end(1)
    return "".join(parts) + html[at:]


def minify_html_file(path: Path) -> None:
    html = path.read_text(encoding="utf-8")
    all_scripts = len(re.findall(r"<script\b", html))
    bare_scripts = len(re.findall(r"<script>", html))
    jsonld_scripts = html.count(JSONLD_TAG)
    if all_scripts != bare_scripts + jsonld_scripts:
        sys.exit(f"build_site: {path} has an unsupported <script> with attributes; teach build_site about it")
    html = splice_jsonld(html)
    html = splice(html, "script", "js")
    html = splice(html, "style", "css")
    for m in re.finditer(r"<script>(.*?)</script>", html, re.S):
        body = m.group(1)
        if body in _NODE_CHECKED:
            continue
        with tempfile.NamedTemporaryFile("w", suffix=".js", encoding="utf-8") as f:
            f.write(body)
            f.flush()
            subprocess.run(["node", "--check", f.name], check=True)
        _NODE_CHECKED.add(body)
    path.write_text(html, encoding="utf-8")


def latest_release_tag(repo: Path) -> str:
    tags = subprocess.run(
        ["git", "tag", "--list", "v*", "--sort=-v:refname"],
        cwd=repo, capture_output=True, text=True, check=True,
    ).stdout.split()
    return tags[0] if tags else "main"


def installer_targets(install_sh: str) -> set[str]:
    """The target triples the installer's platform arms select (`target=TRIPLE` lines)."""
    return set(re.findall(r"^\s*target=([A-Za-z0-9_.-]+)\s*$", install_sh, re.M))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--hirsel-repo", type=Path, default=os.environ.get("HIRSEL_REPO"),
                        help="checkout of SamGalanakis/hirsel (default: $HIRSEL_REPO)")
    parser.add_argument("--installer", type=Path, required=True, metavar="INSTALL_SH",
                        help="the release's install.sh, already checked against its SHA256SUMS")
    parser.add_argument("--out", type=Path, default=Path("_site"))
    parser.add_argument("--release-tag", metavar="TAG",
                        help="align the docs to TAG (default: newest v* tag; `main` for the working tree)")
    args = parser.parse_args()
    if args.hirsel_repo is None:
        parser.error("pass --hirsel-repo or set HIRSEL_REPO")
    repo = args.hirsel_repo.resolve()
    os.environ["HIRSEL_REPO"] = str(repo)
    ref = args.release_tag or latest_release_tag(repo)
    if (SITE / "install.sh").exists():
        sys.exit("build_site: site/install.sh must not exist; the installer comes from the release (--installer)")
    install_sh = args.installer.read_text(encoding="utf-8")
    targets = installer_targets(install_sh)
    if targets != SUPPORTED_TARGETS:
        sys.exit(
            f"build_site: {args.installer} installs {sorted(targets)} but the site names "
            f"{sorted(SUPPORTED_TARGETS)}; update the platform copy and SUPPORTED_TARGETS together"
        )
    print(f"build_site: docs from {repo} at {ref}", file=sys.stderr)
    out = args.out
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(SITE, out)
    shutil.copyfile(args.installer, out / "install.sh")
    subprocess.run([sys.executable, str(TOOLS / "site_sync.py"), "--ref", ref, "--out-dir", str(out)], check=True)
    tag = [] if ref == "main" else ["--release-tag", ref]
    subprocess.run([sys.executable, str(TOOLS / "site_docs.py"), "--out-dir", str(out), *tag], check=True)
    for html_path in sorted(out.rglob("*.html")):
        minify_html_file(html_path)


if __name__ == "__main__":
    main()
